import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage();
p.on('console', (m) => m.type() === 'error' && console.log('console:', m.text()));
p.on('pageerror', (e) => console.log('pageerror:', e.message, e.stack));
await p.goto('data:text/html,<html></html>');
await p.addScriptTag({ path: process.argv[2] });
const r = await p.evaluate(async () => {
  const h = (method, url, body, headers = {}) => window.auroraDemo.handle({ method, url, body, headers });
  const out = {};
  out.health = (await h('GET', '/health')).body;
  const projects = (await h('GET', '/api/v1/projects')).body;
  out.projects = projects.map((x) => x.name);
  const pid = projects[0].id;
  const d = (await h('GET', `/api/v1/projects/${pid}/formula-draft`)).body;
  out.total = d.computed.totalPct;
  const v = await h('POST', `/api/v1/projects/${pid}/formula-versions`, { expectedDraftRevision: d.revision, versionLabel: 'Demo V1' });
  out.save = [v.status, v.body.snapshotHash?.slice(0, 12)];
  out.dup = (await h('POST', `/api/v1/projects/${pid}/formula-versions`, { expectedDraftRevision: d.revision, versionLabel: 'Demo V1' })).status;
  out.bad = (await h('PUT', `/api/v1/projects/${pid}/formula-draft`, { revision: 'x' })).body.code;
  const run = await h('POST', '/api/v1/validations', { formulaVersionId: v.body.id, market: 'EU', category: 'Fine fragrance (hydroalcoholic)' });
  out.validation = [run.status, run.body.status];
  out.viewer = (await h('PUT', `/api/v1/projects/${pid}/formula-draft`, { revision: d.revision, items: [] }, { 'x-aurora-user': '6f1c2a5e-0000-4000-8000-000000000004' })).status;
  out.ai = (await h('POST', '/api/v1/ai/proposals', {})).status;
  out.ing = (await h('GET', '/api/v1/ingredients?q=berg')).body.total;
  return out;
});
console.log(JSON.stringify(r, null, 1));
await b.close();
