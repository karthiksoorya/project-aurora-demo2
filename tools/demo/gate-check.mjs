import { chromium } from '@playwright/test';
const [base, out] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1672, height: 941 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(base + '/projects/449b5ed1-d098-5f91-9839-006e26c6dd99/formula');
await p.getByTestId('access-gate').waitFor();
await p.screenshot({ path: `${out}/gate.png` });
await p.getByTestId('access-password').fill('wrong');
await p.getByTestId('access-submit').click();
const err = await p.getByTestId('access-error').innerText();
await p.getByTestId('access-password').fill('sea-breeze');
await p.getByTestId('access-submit').click();
await p.getByTestId('workspace-title').waitFor({ timeout: 30000 });
const title = await p.getByTestId('workspace-title').innerText();
await p.screenshot({ path: `${out}/after-login.png` });
console.log(JSON.stringify({ err, title, url: p.url(), errs }));
await b.close();
